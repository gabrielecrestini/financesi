function changeLanguage(lang) {
    if (!translations[lang]) lang = 'it';
    currentLang = lang;
    localStorage.setItem('preferredLang', lang); 
    
    const tr = translations[lang];
    
    document.documentElement.lang = lang;
    
    // Imposta il titolo della pagina corretto
    const pageId = document.body.id;
    if (pageId === 'page-index') document.title = tr.pageTitleIndex;
    else if (pageId === 'page-teoria') document.title = tr.pageTitleTeoria;
    else if (pageId === 'page-dispense') document.title = tr.pageTitleDispense;
    else if (pageId === 'page-pratica') document.title = tr.pageTitlePratica;
    
    document.querySelectorAll('[data-lang-key]').forEach(el => {
        const key = el.dataset.langKey;
        if (tr[key]) {
            el.innerHTML = tr[key];
        }
    });
    
    langButtons.forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });
    
    setupScrollAnimations();
    
    // Ricarica i componenti dinamici della pagina corrente
    if (document.body.id === 'page-index') {
        setupHomepage();
    } else if (document.body.id === 'page-teoria') {
        // Nessun dato da ricaricare, solo testo
    } else if (document.body.id === 'page-dispense') {
        populateRisorse(lang);
        const faqAnswers = document.querySelectorAll('.faq-answer');
        faqAnswers.forEach(answer => { answer.style.maxHeight = null; });
        document.querySelectorAll('.faq-item').forEach(item => { item.classList.remove('active'); });
    } else if (document.body.id === 'page-pratica') {
        fetchPrezzi(); 
        loadTradingViewWidget(lang); 
    }
}

