async function fetchPrezzi() {
    const mercatoList = document.getElementById('mercato-list');
    if (!mercatoList) return; // Non siamo nella pagina pratica
    
    try {
        const response = await fetch(API_URL);
        if (!response.ok) throw new Error(`API Error: ${response.status}`);
        const data = await response.json();
        if (Object.keys(data).length === 0) throw new Error("API data empty");
        prezziAttuali = data;
        renderMercato();
        renderPortafoglio();
    } catch (error) {
        console.error("Errore API Coingecko:", error);
        const tr = translations[currentLang] || translations['it']; 
        mercatoList.innerHTML = `<p style="color: var(--danger-color); font-weight: 600;">${tr.simApiError}</p>`;
    }
}

