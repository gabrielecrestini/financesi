function eseguiTransazione() {
    const tr = translations[currentLang];
    const modalInput = document.getElementById('modal-input');
    const modalError = document.getElementById('modal-error');
    const importoEuro = parseFloat(modalInput.value);
    const prezzo = parseFloat(modalData.prezzo);
    const id = modalData.id;
    
    if (isNaN(importoEuro) || importoEuro <= 0) {
        modalError.innerText = tr.simErrorAmount;
        modalError.style.display = 'block';
        return;
    }
    
    if (modalData.tipo === 'compra') {
        if (importoEuro > portafoglio.liquidi) {
            modalError.innerText = tr.simErrorCash;
            modalError.style.display = 'block';
            return;
        }
        const quantitaCrypto = importoEuro / prezzo;
        portafoglio.liquidi -= importoEuro;
        portafoglio.crypto[id] = (portafoglio.crypto[id] || 0) + quantitaCrypto;
    } else if (modalData.tipo === 'vendi') {
        const quantitaCryptoDaVendere = importoEuro / prezzo;
        const quantitaPosseduta = portafoglio.crypto[id] || 0;
        
        if (quantitaCryptoDaVendere > (quantitaPosseduta + 1e-9)) {
            modalError.innerText = tr.simErrorAsset.replace('{symbol}', modalData.simbolo.toUpperCase());
            modalError.style.display = 'block';
            return;
        }
        portafoglio.liquidi += importoEuro;
        portafoglio.crypto[id] -= quantitaCryptoDaVendere;
    }
    savePortafoglio();
    chiudiModal();
}

function chiudiModal() {
    const modal = document.getElementById('sim-modal');
    if (modal) modal.style.display = "none";
}

