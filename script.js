// --- LOGICA NAVIGAZIONE A SCHEDE (TABS) ---
function setupTabs() {
    const tabButtons = document.querySelectorAll('.tab-button');
    const tabPanels = document.querySelectorAll('.tab-panel');
    const skipLinks = document.querySelectorAll('.skip-link');
    const nextButtons = document.querySelectorAll('.btn-avanti-tappa');

    function showTab(tabId) {
        if (!tabId) return;
        
        tabButtons.forEach(btn => {
            btn.classList.toggle('active', btn.dataset.tab === tabId);
        });
        tabPanels.forEach(panel => {
            panel.classList.toggle('active', panel.id === tabId);
        });
        
        // Carica gli script solo quando la scheda "Pratica" è visibile
        if (tabId === 'pratica') {
            if (typeof loadTradingViewWidget === 'function') loadTradingViewWidget(currentLang);
            if (typeof fetchPrezzi === 'function') fetchPrezzi();
        }
        
        window.scrollTo(0, 0); // Torna in cima al cambio scheda
    }

    tabButtons.forEach(button => {
        button.addEventListener('click', () => {
            showTab(button.dataset.tab);
        });
    });
    
    skipLinks.forEach(link => {
        link.addEventListener('click', (e) => {
             e.preventDefault();
            showTab(link.dataset.tab);
        });
    });
    
    nextButtons.forEach(button => {
        button.addEventListener('click', (e) => {
             e.preventDefault();
            showTab(button.dataset.tab);
        });
    });
}
        
