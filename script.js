function renderPortafoglio() {
    const tr = translations[currentLang] || translations['it'];
    const portfolioAssetsEl = document.getElementById('portfolio-assets');
    const portfolioValoreTotaleEl = document.getElementById('portfolio-valore-totale');
    const portfolioLiquidiEl = document.getElementById('portfolio-liquidi');
    
    if (!portfolioAssetsEl) return; 
    
    let valoreCryptoTotale = 0;
    portfolioAssetsEl.innerHTML = ''; 
    let hasAssets = false;
    
    for (const id in portafoglio.crypto) {
        const quantita = portafoglio.crypto[id];
        if (quantita > 1e-9 && prezziAttuali[id]) { 
            hasAssets = true;
            const prezzo = prezziAttuali[id].eur;
            const valoreAttuale = quantita * prezzo;
            valoreCryptoTotale += valoreAttuale;
            
            const item = document.createElement('div');
            item.className = 'asset-item';
            item.innerHTML = `
                <div class="asset-nome">${id.charAt(0).toUpperCase() + id.slice(1)}</div>
                <div class="asset-valore">
                    ${formatCurrency(valoreAttuale)}
                    <span>${formatCrypto(quantita)} ${id.toUpperCase()}</span>
                </div>
            `;
            portfolioAssetsEl.appendChild(item);
        } else if (quantita <= 1e-9) {
             delete portafoglio.crypto[id]; 
        }
    }
    
    if (!hasAssets) {
        portfolioAssetsEl.innerHTML = `<p>${tr.simNoAssets}</p>`;
    }
    
    const valoreTotale = portafoglio.liquidi + valoreCryptoTotale;
    portfolioValoreTotaleEl.innerText = formatCurrency(valoreTotale);
    portfolioLiquidiEl.innerText = formatCurrency(portafoglio.liquidi);
}

